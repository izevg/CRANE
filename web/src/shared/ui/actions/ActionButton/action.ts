/**
 * Единое описание действия пользователя. Из него строятся кнопка, пункт меню, подвал панели и палитра:
 * правило «кнопка есть ⇔ передана ссылка или обработчик» живёт в одном месте.
 */
export type Action = {
  label: string;
  /** Переход (рендерится ссылкой) или обработчик (рендерится кнопкой). */
  run: { href: string } | { onSelect: () => void };
  /** Только из `denied_actions`: действие недоступно, причина показывается и читается скринридером. */
  disabledReason?: string;
  /** Действие требует повторного подтверждения входа: бейдж «MFA» и пометка в доступном имени. */
  stepUp?: true;
  /** Опасное действие: текст error-тона без заливки; в меню идёт последним, за разделителем. */
  destructive?: true;
};
