//! Адаптер Valkey: общий кэш записей proxy (`ProxyCache`) и межрепликовый singleflight
//! (`FetchLeases`) в одном типе [`Valkey`].
//!
//! Внутри два уровня: L2 в Valkey и L1 (moka) в процессе. Когерентность L1 между репликами
//! держит pub/sub-канал `inv`: каждая запись и каждое снятие lease публикуют имя ключа,
//! а диспетчер каждой реплики выбрасывает его из своего L1 и будит ждущих.
//!
//! Valkey не влияет на готовность процесса: `start` не ждёт подключения, а при недоступном
//! сервере команды быстро возвращают ошибку (кэш — не источник истины).

